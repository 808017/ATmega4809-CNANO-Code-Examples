#include <xc.h>
#include <stdint.h>

#include "i2c.h"
#include "oled.h"

#define OLED_ADDR       0x3D

#define OLED_WIDTH      128
#define OLED_PAGES      8

#define OLED_COMMAND    0x00
#define OLED_DATA       0x40

static void OLED_WriteCommand(uint8_t command)
{
    if (!I2C_StartWrite(OLED_ADDR))
    {
        I2C_Stop();
        return;
    }

    I2C_WriteByte(OLED_COMMAND);
    I2C_WriteByte(command);

    I2C_Stop();
}

static void OLED_WriteData(uint8_t data)
{
    if (!I2C_StartWrite(OLED_ADDR))
    {
        I2C_Stop();
        return;
    }

    I2C_WriteByte(OLED_DATA);
    I2C_WriteByte(data);

    I2C_Stop();
}

void OLED_SetCursor(uint8_t page, uint8_t column)
{
    OLED_WriteCommand(0xB0 | page);
    OLED_WriteCommand(0x00 | (column & 0x0F));
    OLED_WriteCommand(0x10 | ((column >> 4) & 0x0F));
}

void OLED_Clear(void)
{
    uint8_t page;
    uint8_t column;

    for (page = 0; page < OLED_PAGES; page++)
    {
        OLED_SetCursor(page, 0);

        for (column = 0; column < OLED_WIDTH; column++)
        {
            OLED_WriteData(0x00);
        }
    }
}

void OLED_Init(void)
{
    OLED_WriteCommand(0xAE); // Display OFF

    OLED_WriteCommand(0xD5);
    OLED_WriteCommand(0x80); // Display clock divide

    OLED_WriteCommand(0xA8);
    OLED_WriteCommand(0x3F); // 128x64 multiplex

    OLED_WriteCommand(0xD3);
    OLED_WriteCommand(0x00); // Display offset

    OLED_WriteCommand(0x40); // Start line 0

    OLED_WriteCommand(0x8D);
    OLED_WriteCommand(0x14); // Enable charge pump

    OLED_WriteCommand(0x20);
    OLED_WriteCommand(0x02); // Page addressing mode

    OLED_WriteCommand(0xA1); // Segment remap

    OLED_WriteCommand(0xC8); // COM scan direction

    OLED_WriteCommand(0xDA);
    OLED_WriteCommand(0x12); // COM pin configuration

    OLED_WriteCommand(0x81);
    OLED_WriteCommand(0x7F); // Contrast

    OLED_WriteCommand(0xD9);
    OLED_WriteCommand(0xF1); // Pre-charge

    OLED_WriteCommand(0xDB);
    OLED_WriteCommand(0x40); // VCOMH level

    OLED_WriteCommand(0xA4); // Display follows RAM

    OLED_WriteCommand(0xA6); // Normal display

    OLED_Clear();

    OLED_WriteCommand(0xAF); // Display ON
}

