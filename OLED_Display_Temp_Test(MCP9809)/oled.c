void OLED_WriteChar(char c)
{
    uint8_t i;

    if (c < 0 || c > 127)
    {
        c = ' ';
    }

    for (i = 0; i < 5; i++)
    {
        OLED_WriteData(font5x7[(uint8_t)c][i]);
    }

    OLED_WriteData(0x00); // Space between characters
}

void OLED_WriteString(const char *text)
{
    while (*text)
    {
        OLED_WriteChar(*text++);
    }
}